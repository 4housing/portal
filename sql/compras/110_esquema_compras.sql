-- 5.a · Tablas "genéricas" de Compras: acceso total al sector compras.
do $$
declare t text;
begin
  foreach t in array array[
    'compras_articulos','compras_certificadores','compras_clasif_comprobantes',
    'compras_depositos','compras_herr_operaciones','compras_herramientas',
    'compras_inspecciones','compras_mantenimiento','compras_modulos',
    'compras_motivos_cierre','compras_oc_informe','compras_og_certificados',
    'compras_ogs','compras_opciones_og','compras_panol_egresos',
    'compras_proveedores','compras_proyectos','compras_series',
    'compras_series_activas','compras_solicitudes_pago','compras_stock_saldos',
    'compras_idx_cac','compras_idx_dolar_blue','compras_idx_dolar_oficial',
    'compras_idx_ipc','compras_idx_poli','compras_idx_uva'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('drop policy if exists compras_sector on public.%I', t);
    execute format($f$create policy compras_sector on public.%I
                     for all to authenticated
                     using (public.tiene_sector('compras'::public.sector_portal))
                     with check (public.tiene_sector('compras'::public.sector_portal))$f$, t);
  end loop;
end $$;

-- 5.b · Tablas de referencia que EERR también LEE (compras+eerr select; compras write).
do $$
declare t text;
begin
  foreach t in array array[
    'compras_usd_diario','compras_usd_diario_oficial',
    'compras_idx_facpce','compras_clasif_renglon'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('drop policy if exists compras_ref_sel on public.%I', t);
    execute format('drop policy if exists compras_ref_write on public.%I', t);
    execute format($f$create policy compras_ref_sel on public.%I
                     for select to authenticated
                     using (public.tiene_sector('compras'::public.sector_portal)
                         or public.tiene_sector('eerr'::public.sector_portal))$f$, t);
    execute format($f$create policy compras_ref_write on public.%I
                     for all to authenticated
                     using (public.tiene_sector('compras'::public.sector_portal))
                     with check (public.tiene_sector('compras'::public.sector_portal))$f$, t);
  end loop;
end $$;


    from public.compras_usuarios_autorizados;

-- ===========================================================================
-- 4 · Helper de flags internos de Compras (security definer → no depende del
--     RLS de compras_usuarios_autorizados). Devuelve el flag del usuario actual.
-- ===========================================================================
create or replace function public.compras_flag(p_flag text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((
    select case p_flag
             when 'tesorero'     then u.es_tesorero
             when 'confidencial' then u.ve_confidencial
             when 'admin'        then u.es_admin
             when 'certificador' then u.es_certificador
             when 'comprador'    then u.es_comprador
             when 'finanzas'     then u.es_finanzas
             else false
           end
      from public.compras_usuarios_autorizados u
     where u.email = (auth.jwt() ->> 'email')
  ), false);
$$;
revoke all on function public.compras_flag(text) from public, anon;
grant execute on function public.compras_flag(text) to authenticated;


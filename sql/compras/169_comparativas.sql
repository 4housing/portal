-- ============================================================================
-- Portal 4housing · 169 · Compras · Comparativas de compra (3+ proveedores)
-- ============================================================================
-- Homogeneíza las comparativas por material: se cargan 3+ ofertas y la app calcula
-- el "precio homogeneizado" (a sin IVA, una moneda con TC, valor contado según la
-- condición de pago, y por unidad de comparación), marca el más barato, muestra un
-- puntaje ponderado (precio/plazo/evaluación) como guía, y la decisión final +
-- justificación la carga el comprador. Queda registrada y linkeable a la SOLP/OC.
--
-- Decisiones (Pablo): tasa financiera editable por comparativa · base SIN IVA ·
-- USD y Pesos con TC BNA vendedor billete del día (override por oferta) · flete
-- prorrateado · mínimo 3 ofertas para decidir · puntaje guía + decisión del comprador.
--
-- Correr en wcpk. Idempotente. RLS: sector compras.
-- ============================================================================

-- Cabecera: la necesidad + parámetros de normalización + la decisión.
create table if not exists public.compras_comparativas (
  id               bigint generated by default as identity primary key,
  codigo           text,                 -- N° de obra / proyecto (match con GP)
  solp_id          bigint,               -- SOLP de origen (opcional)
  solp_num         text,                 -- N° de SOLP visible (opcional)
  material         text not null,
  cantidad         numeric default 0,
  unidad           text,                 -- unidad de comparación (m, kg, unidad…)
  fecha_necesidad  date,
  -- parámetros de normalización
  tasa_mensual     numeric default 0,    -- % mensual para llevar a valor contado (ej. 0.04)
  tc_default       numeric,              -- TC BNA vendedor billete del día (snapshot; override por oferta)
  base_iva         text default 'sin_iva',
  -- pesos del puntaje guía (editables)
  peso_precio      numeric default 0.60,
  peso_plazo       numeric default 0.20,
  peso_eval        numeric default 0.20,
  -- decisión (del comprador)
  elegido_oferta_id bigint,
  justificacion    text,
  estado           text default 'abierta',   -- 'abierta' | 'decidida'
  decidido_por     text,
  decidido_en      timestamptz,
  creado_por       text,
  creado_en        timestamptz not null default now()
);
create index if not exists compras_comparativas_codigo on public.compras_comparativas(codigo);
create index if not exists compras_comparativas_solp   on public.compras_comparativas(solp_id);

-- Ofertas: una fila por proveedor cotizante.
create table if not exists public.compras_comparativa_ofertas (
  id               bigint generated by default as identity primary key,
  comparativa_id   bigint not null references public.compras_comparativas(id) on delete cascade,
  proveedor_cod    text,
  proveedor        text,
  presentacion     text,                 -- ej. "barra 6 m", "por metro", "balde 20 kg"
  precio           numeric default 0,    -- precio de la presentación cotizada
  factor           numeric default 1,    -- presentación -> unidad de comparación (ej. 1 barra = 6)
  moneda           text default 'ARS',   -- 'ARS' | 'USD'
  tc               numeric,              -- override del TC para esta oferta (null = usa tc_default)
  iva_incluido     boolean default false,
  bonif_pct        numeric default 0,
  cond_pago_dias   int default 0,        -- 0 = contado; 30/60/90…
  plazo_entrega_dias int,
  validez          date,
  flete            numeric default 0,    -- costo de flete (total de la oferta)
  flete_incluido   boolean default true, -- si true, no se suma aparte
  observaciones    text,
  adjunto_url      text,                 -- PDF de la oferta (SharePoint)
  precio_homogeneizado numeric,          -- snapshot calculado por la app (para registro/PDF)
  creado_en        timestamptz not null default now()
);
create index if not exists compras_comp_ofertas_comp on public.compras_comparativa_ofertas(comparativa_id);

-- RLS: authenticated + sector compras (mismo patrón que compras_gp_*).
do $$
declare t text;
begin
  foreach t in array array['compras_comparativas','compras_comparativa_ofertas'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('drop policy if exists compras_comp_sector on public.%I', t);
    execute format($f$create policy compras_comp_sector on public.%I
                     for all to authenticated
                     using (public.tiene_sector('compras'::public.sector_portal))
                     with check (public.tiene_sector('compras'::public.sector_portal))$f$, t);
  end loop;
end $$;
